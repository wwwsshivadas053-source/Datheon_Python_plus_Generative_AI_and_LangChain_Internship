"""Robust JSON Extraction and Self-Healing Engine.

Handles malformed markdown envelopes, non-standard quotes, comments,
trailing commas, and unbalanced boundary tokens often generated by LLMs.
"""

import json
import re
from typing import Any, Dict, Optional, Tuple


class JSONCleaner:
    """Multi-tiered JSON extraction, normalization, and repair pipeline."""

    @staticmethod
    def strip_markdown(text: str) -> str:
        """Extract JSON contents enclosed in markdown code fences."""
        text = text.strip()
        # Match ```json ... ``` or ``` ... ```
        json_fence_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text, re.IGNORECASE)
        if json_fence_match:
            return json_fence_match.group(1).strip()
        return text

    @staticmethod
    def extract_outermost_json_braces(text: str) -> Optional[str]:
        """Locate the outermost balanced curly braces { ... } ignoring internal strings."""
        start_idx = text.find("{")
        if start_idx == -1:
            return None

        depth = 0
        in_string = False
        escape_next = False
        end_idx = -1

        for i in range(start_idx, len(text)):
            char = text[i]

            if escape_next:
                escape_next = False
                continue

            if char == "\\":
                escape_next = True
                continue

            if char == '"':
                in_string = not in_string
                continue

            if not in_string:
                if char == "{":
                    depth += 1
                elif char == "}":
                    depth -= 1
                    if depth == 0:
                        end_idx = i
                        break

        if depth == 0 and end_idx != -1:
            return text[start_idx : end_idx + 1]

        return None

    @staticmethod
    def sanitize_common_syntax_errors(text: str) -> str:
        """Fix smart quotes, trailing commas, comments, and common LLM syntax slip-ups."""
        # Normalize fancy/smart unicode quotes
        replacements = {
            "“": '"',
            "”": '"',
            "‘": "'",
            "’": "'",
            "«": '"',
            "»": '"',
        }
        for orig, target in replacements.items():
            text = text.replace(orig, target)

        # Remove single-line JS/C++ comments (// ...) outside strings
        # Simplified regex for comments on lines
        lines = []
        for line in text.splitlines():
            stripped = line.strip()
            if stripped.startswith("//") or stripped.startswith("#"):
                continue
            lines.append(line)
        text = "\n".join(lines)

        # Remove trailing commas before closing braces or brackets: [1, 2, ] -> [1, 2]
        text = re.sub(r",\s*([\]}])", r"\1", text)

        return text

    @classmethod
    def extract_and_parse(cls, raw_llm_output: str) -> Tuple[Dict[str, Any], str]:
        """Attempt multi-stage parsing: direct -> markdown strip -> bracket slice -> syntax repair.

        Returns:
            Tuple of (parsed_dictionary, cleaned_json_string)

        Raises:
            ValueError: If unable to parse valid JSON after all tiers.
        """
        if not raw_llm_output or not raw_llm_output.strip():
            raise ValueError("LLM returned empty or whitespace-only response.")

        candidates = []

        # Candidate 1: Raw output directly
        candidates.append(raw_llm_output.strip())

        # Candidate 2: Stripped markdown fences
        stripped = cls.strip_markdown(raw_llm_output)
        if stripped not in candidates:
            candidates.append(stripped)

        # Candidate 3: Outermost balanced braces
        braced = cls.extract_outermost_json_braces(stripped)
        if braced and braced not in candidates:
            candidates.append(braced)

        # Candidate 4: Syntax sanitized versions
        sanitized_cands = []
        for cand in candidates:
            sanitized = cls.sanitize_common_syntax_errors(cand)
            if sanitized not in candidates and sanitized not in sanitized_cands:
                sanitized_cands.append(sanitized)
        candidates.extend(sanitized_cands)

        last_error = None
        for cand in candidates:
            try:
                parsed = json.loads(cand)
                if isinstance(parsed, dict):
                    return parsed, cand
            except json.JSONDecodeError as err:
                last_error = err

        # If all candidates fail, raise descriptive error
        preview = (raw_llm_output[:250] + "...") if len(raw_llm_output) > 250 else raw_llm_output
        raise ValueError(
            f"Failed to extract valid JSON from LLM response. Last error: {last_error}.\n"
            f"Raw output snippet: {preview}"
        )
